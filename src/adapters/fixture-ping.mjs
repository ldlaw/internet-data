// SYNTHETIC test data for the Gate 2B hosting rehearsal (GitHub Actions, Pages, CORS, caching, kill switch).
// No network, no provider, no measurement: every value comes from a seeded model of great-circle distance. The result goes through the SAME
// normalize() and the same gates as real data, so the rehearsal exercises the real pipeline; it is marked simulated in five independent places
// (see syntheticRules in contract.mjs). Endpoint names reuse the planned anchor cities for realism only; ids are in a reserved range no real id has reached.
import { hav, SYNTHETIC_ID_BASE } from '../contract.mjs';
import { normalize, POLICY } from './ripe-atlas-ping.mjs';
import { FetchFailed } from '../http.mjs';

export const REPO_URL = 'https://github.com/ldlaw/internet-data';
export const PROVIDER = { id: 'fixture', name: 'Synthetic test data', operator: 'No provider (simulation)', url: REPO_URL, terms_url: REPO_URL, attribution: 'SIMULATED data generated by the collector for hosting tests. Not real measurements.' };
export const DATASET_ID = 'synthetic-test-fixture';
export const COLLECTOR_VERSION = '0.0.0-gate2b';
// Faults exist to rehearse the failure gates. Each one makes the run fail BEFORE deploy, so the previous deployment stays online.
export const FAULTS = ['none', 'validation', 'quality', 'permission', 'collection'];

const prng = (seed) => () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; };
const hash = (s) => [...s].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);

// Same node list, but only the public city data is kept. Ids move to the reserved range and the "target address" is a documentation-range placeholder that is never published.
export function syntheticConfig(nodesCfg) {
  return { dataset_id: DATASET_ID, nodes: nodesCfg.nodes.map((n, i) => ({ id: n.id, label: n.label, country: n.country, lat: n.lat, lon: n.lon,
    anchor_id: SYNTHETIC_ID_BASE + 1 + i, probe_id: SYNTHETIC_ID_BASE + 101 + i, measurement_id: SYNTHETIC_ID_BASE + 201 + i, target_ip: `192.0.2.${i + 1}` })) };
}

export function syntheticRaw(config, { now, dropNodes = [] }) {
  const out = new Map();
  for (const dst of config.nodes) {
    const rows = [];
    for (const src of config.nodes) {
      if (src.id === dst.id || dropNodes.includes(src.id) || dropNodes.includes(dst.id)) continue;
      const rnd = prng(hash(src.id + '>' + dst.id)), base = Math.max(0.4, hav(src, dst) / 100 * (1.25 + rnd() * 0.8)), age = 60 + Math.floor(rnd() * 420), lossy = hash(src.id + dst.id) % 9 === 0;
      for (let k = 0; k < POLICY.windowResults; k++) {
        const rcvd = lossy && k === 0 ? 2 : 3, rtt = base + (rnd() - 0.5) * 0.5, rs = [0, 0.07, 0.14].slice(0, rcvd).map((d) => +(rtt + d).toFixed(3));
        rows.push({ prb_id: src.probe_id, msm_id: dst.measurement_id, dst_addr: dst.target_ip, timestamp: Math.floor(now - age - k * 240 - rnd() * 40), sent: 3, rcvd, lts: 60,
          min: Math.min(...rs), max: Math.max(...rs), avg: +(rs.reduce((a, b) => a + b, 0) / rs.length).toFixed(6) });
      }
    }
    out.set(dst.id, rows);
  }
  return out;
}

export function collectSynthetic(nodesCfg, { nowSeconds, fetchedAt, fault = 'none' }) {
  if (!FAULTS.includes(fault)) throw new Error(`unknown fault ${JSON.stringify(fault)}`);
  if (fault === 'collection') throw new FetchFailed('simulated provider outage (fault injection)', 'synthetic://fixture');
  const config = syntheticConfig(nodesCfg), ids = config.nodes.map((n) => n.id).sort();
  const raw = syntheticRaw(config, { now: nowSeconds, dropNodes: fault === 'quality' ? ids.slice(0, 6) : [] });
  const dataset = normalize(raw, config, { generatedAt: nowSeconds, fetchedAt, collectorVersion: COLLECTOR_VERSION, permissionStatus: 'synthetic', provider: PROVIDER, simulated: true, datasetId: DATASET_ID,
    method: { kind: 'ping', protocol: 'ICMP', af: 4, interval_s: 240, packets_per_result: POLICY.packets, window_results_max: POLICY.windowResults, selection: 'SIMULATED values from a seeded distance model: no provider, no network, no measurement', api: REPO_URL },
    notes: ['SIMULATED TEST DATA. These are not measurements. They exist to test hosting, caching and the kill switch.', 'City names reuse the planned anchor locations for realism only. No anchor or probe was contacted and every identifier is in a reserved synthetic range.'] });
  if (fault === 'validation') dataset.observations[0].loss.rcvd = dataset.observations[0].loss.sent + 5;       // arithmetic the contract must reject
  if (fault === 'permission') dataset.provenance.provider = { ...dataset.provenance.provider, id: 'ripe-atlas' };   // synthetic data claiming a real provider must be refused
  return dataset;
}
